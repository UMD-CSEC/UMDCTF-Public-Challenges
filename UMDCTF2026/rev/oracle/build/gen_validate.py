#!/usr/bin/env python3
"""Emit vm_src/validate.vmasm + build/validate_ticket.bin.

8-register, 8-round keyed permutation (XOR, ADD, ROL, cross-reg XOR/ADD,
MUL by odd constant — each step invertible). Compares final state to a
target vector baked into the class's const pool; on exact match the VM
returns hash_x(ticket || SALT).

Script mode: pick random RK + ticket, compute TARGET, emit vmasm and the
winning ticket. Import mode: exposes only forward/inverse/constants."""
import os, struct, secrets, sys

sys.path.insert(0, os.path.dirname(__file__))
from hashx import hash_x

N_REGS = 8
N_ROUNDS = 8
ODD_MUL = 0x5ABC7F01      # odd so invertible mod 2^32
SALT = b'umdctf-v2026-unseal-salt'

MASK32 = 0xFFFFFFFF
ODD_MUL_INV = pow(ODD_MUL, -1, 1 << 32)

def rol32(x, n):
    n &= 31
    return ((x << n) | (x >> (32 - n))) & MASK32 if n else x & MASK32

def ror32(x, n):
    n &= 31
    return ((x >> n) | (x << (32 - n))) & MASK32 if n else x & MASK32

def round_slots(i):
    base = (5 * i + 1)
    return [(base + k * 3) % N_REGS for k in range(7)]

def round_rot(i):
    return ((i * 7) + 3) & 31

def forward_round(regs, RK, i):
    slots = round_slots(i)
    s0, s1, s2, s3, s4, s5, s7 = slots[0], slots[1], slots[2], slots[3], slots[4], slots[5], slots[6]
    regs[s0] ^= RK[i*2 + 0]; regs[s0] &= MASK32
    regs[s1] = (regs[s1] + RK[i*2 + 1]) & MASK32
    regs[s2] = rol32(regs[s2], round_rot(i))
    regs[s3] ^= regs[s4]; regs[s3] &= MASK32
    regs[s5] = (regs[s5] + regs[(s5 + 1) % N_REGS]) & MASK32
    regs[s7] = (regs[s7] * ODD_MUL) & MASK32

def inverse_round(regs, RK, i):
    slots = round_slots(i)
    s0, s1, s2, s3, s4, s5, s7 = slots[0], slots[1], slots[2], slots[3], slots[4], slots[5], slots[6]
    regs[s7] = (regs[s7] * ODD_MUL_INV) & MASK32
    regs[s5] = (regs[s5] - regs[(s5 + 1) % N_REGS]) & MASK32
    regs[s3] ^= regs[s4]; regs[s3] &= MASK32
    regs[s2] = ror32(regs[s2], round_rot(i))
    regs[s1] = (regs[s1] - RK[i*2 + 1]) & MASK32
    regs[s0] ^= RK[i*2 + 0]; regs[s0] &= MASK32

def forward(ticket_bytes, RK):
    regs = list(struct.unpack('<8I', ticket_bytes))
    for i in range(N_ROUNDS):
        forward_round(regs, RK, i)
    return regs

def inverse(target_regs, RK):
    regs = list(target_regs)
    for i in range(N_ROUNDS - 1, -1, -1):
        inverse_round(regs, RK, i)
    return struct.pack('<8I', *regs)


def _emit_vmasm(RK, TARGET):
    RK_bytes     = struct.pack(f'<{len(RK)}I', *RK)
    TARGET_bytes = struct.pack(f'<{len(TARGET)}I', *TARGET)
    out = []
    out.append('; AUTO-GENERATED by build/gen_validate.py — do not hand-edit.')
    out.append('; Heavy validation path: 8 u32 registers put through 8 invertible rounds.')
    out.append('; On an exact match with TARGET, emits flag_km = hash_x(ticket || SALT).')
    out.append('')
    out.append('.encrypt 0xDAB1')
    out.append(f'.const_hex {RK_bytes.hex()}')
    out.append(f'.const_hex {TARGET_bytes.hex()}')
    out.append(f'.const "{SALT.decode()}"')
    out.append('')

    out.append('; === Phase 1: unpack 32-byte ticket into regs[0..7] ===')
    for i in range(N_REGS):
        out.append('PUSH_GLB    INNER_MSG')
        out.append(f'PUSH_I32    {i*4}')
        out.append('BSTR_LOAD_U32')
        out.append(f'STORE_REG   {i}')
    out.append('')

    out.append('; === Phase 2: 8 mixing rounds ===')
    for r in range(N_ROUNDS):
        slots = round_slots(r)
        s0, s1, s2, s3, s4, s5, s7 = slots[0], slots[1], slots[2], slots[3], slots[4], slots[5], slots[6]
        rot = round_rot(r)
        out.append(f'; --- round {r} ---')
        # regs[s0] ^= RK[r*2]
        out.append(f'LOAD_REG    {s0}'); out.append('PUSH_CONST  0')
        out.append(f'PUSH_I32    {r*2*4}'); out.append('BSTR_LOAD_U32')
        out.append('XOR'); out.append(f'STORE_REG   {s0}')
        # regs[s1] += RK[r*2+1]
        out.append(f'LOAD_REG    {s1}'); out.append('PUSH_CONST  0')
        out.append(f'PUSH_I32    {(r*2+1)*4}'); out.append('BSTR_LOAD_U32')
        out.append('ADD'); out.append(f'STORE_REG   {s1}')
        # regs[s2] = ROL(regs[s2], rot)
        out.append(f'LOAD_REG    {s2}'); out.append(f'PUSH_I32    {rot}')
        out.append('ROL'); out.append(f'STORE_REG   {s2}')
        # regs[s3] ^= regs[s4]
        out.append(f'LOAD_REG    {s3}'); out.append(f'LOAD_REG    {s4}')
        out.append('XOR'); out.append(f'STORE_REG   {s3}')
        # regs[s5] += regs[(s5+1)%N]
        out.append(f'LOAD_REG    {s5}'); out.append(f'LOAD_REG    {(s5 + 1) % N_REGS}')
        out.append('ADD'); out.append(f'STORE_REG   {s5}')
        # regs[s7] *= ODD_MUL
        out.append(f'LOAD_REG    {s7}'); out.append(f'PUSH_I32    0x{ODD_MUL:x}')
        out.append('MUL'); out.append(f'STORE_REG   {s7}')
        out.append('')

    out.append('; === Phase 3: regs[i] must equal TARGET[i] for all i ===')
    for i in range(N_REGS):
        out.append(f'LOAD_REG    {i}')
        out.append('PUSH_CONST  1')
        out.append(f'PUSH_I32    {i*4}')
        out.append('BSTR_LOAD_U32')
        out.append('NEQ')
        out.append('JNZ         fail')
    out.append('')

    out.append('; === Phase 4: emit flag_km = hash_x(ticket || SALT) ===')
    out.append('PUSH_GLB    INNER_MSG')
    out.append('PUSH_CONST  2')
    out.append('CONCAT')
    out.append('NATIVE      HASH_X, 1')
    out.append('RET')
    out.append('')
    out.append('fail:')
    out.append('PUSH_I32    0')
    out.append('RET')
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    RK = [secrets.randbits(32) for _ in range(N_ROUNDS * 2)]
    TICKET = secrets.token_bytes(32)
    TARGET = forward(TICKET, RK)
    assert inverse(TARGET, RK) == TICKET, "round function not invertible"

    os.makedirs('vm_src', exist_ok=True)
    with open('vm_src/validate.vmasm', 'w') as f:
        f.write(_emit_vmasm(RK, TARGET))
    print(f'wrote vm_src/validate.vmasm')

    os.makedirs('build', exist_ok=True)
    with open('build/validate_ticket.bin', 'wb') as f:
        f.write(TICKET)
    print(f'wrote build/validate_ticket.bin ({len(TICKET)} bytes)')
