#!/usr/bin/env python3
"""Assemble dist/feed.bin and src/blob_key_table.c.

The feed contains the VM classes, the encrypted flag, and lives behind two
AES-128-CBC layers with per-block key derivation, plus an MWC layer on the
archive body. The flag is AES-encrypted with key material derived from the
specific 32-byte "ticket" that satisfies the validate VM class."""
import os, struct, sys, io, random, secrets, hashlib
from Crypto.Cipher import AES

sys.path.insert(0, os.path.dirname(__file__))
from hashx import hash_x

# Must match gen_validate.py.
SALT = b'umdctf-v2026-unseal-salt'

KEY_TABLE_SIZE = 32
BLOB_BLOCK_SIZE = 64

# Custom archive:
#   magic[4] = "ARC\x01"
#   seed[4]  = LE MWC stream seed
#   body     = MWC(seed) of: n_entries(u8), then {name_len,name,data_len,data}...
def build_archive(entries):
    plain = bytearray()
    plain += bytes([len(entries)])
    for name, data in entries:
        nb = name.encode('ascii')
        assert len(nb) < 256
        plain += bytes([len(nb)])
        plain += nb
        plain += struct.pack('<I', len(data))
        plain += data
    seed_bytes = secrets.token_bytes(4)
    seed = int.from_bytes(seed_bytes, 'little')
    s1 = (0x7FFF7FFF - seed) & 0xFFFFFFFF
    s2 = seed & 0xFFFFFFFF
    body = bytearray(plain)
    for i in range(len(body)):
        s1 = (((s1 & 0xFFFF) * 36969) + (s1 >> 16)) & 0xFFFFFFFF
        s2 = ((s2 >> 16) + (s2 & 0xFFFF) * 18000) & 0xFFFFFFFF
        body[i] ^= (s2 & 0xFF)
    return b'ARC\x01' + seed_bytes + bytes(body)

def encrypt_layer(pt, key_table):
    if len(pt) % 16 != 0:
        pad = 16 - (len(pt) % 16)
        pt = pt + b'\x00' * pad
    header = secrets.token_bytes(BLOB_BLOCK_SIZE)
    out = bytearray(len(pt))
    off = 0
    block_idx = 0
    while off < len(pt):
        chunk = pt[off : off + BLOB_BLOCK_SIZE]
        idx1 = header[(block_idx + 11) & 63] % KEY_TABLE_SIZE
        idx2 = header[(block_idx + 17) & 63] % KEY_TABLE_SIZE
        idx3 = header[block_idx & 63]        % KEY_TABLE_SIZE
        dk = AES.new(key_table[idx3], AES.MODE_ECB).decrypt(key_table[idx1])
        ct = AES.new(dk, AES.MODE_CBC, key_table[idx2]).encrypt(chunk)
        out[off:off + len(chunk)] = ct
        off += len(chunk)
        block_idx += 1
    return header + bytes(out)

def rd(p):
    with open(p, 'rb') as f: return f.read()

def main():
    os.makedirs('dist', exist_ok=True)
    os.makedirs('src',  exist_ok=True)
    os.makedirs('build', exist_ok=True)

    rng = random.Random(0xBADCAFE)

    with open('build/validate_ticket.bin', 'rb') as f:
        TICKET = f.read()
    assert len(TICKET) == 32

    # Flag key derivation must match validate.vmc's trailing hash_x.
    km = hash_x(TICKET + SALT)
    flag_key = km[:16]
    flag_iv  = km[16:32]
    FLAG_PLAINTEXT = b'UMDCTF{oh_no_my_prediction_market_feed_has_been_compromised_what_ever_will_i_do}'
    pad = 16 - (len(FLAG_PLAINTEXT) % 16)
    flag_ct = AES.new(flag_key, AES.MODE_CBC, flag_iv).encrypt(
        FLAG_PLAINTEXT + bytes([pad] * pad))

    entries = [
        ('a', rd('build/vm_out/main.vmc')),
        ('b', rd('build/vm_out/validate.vmc')),
        ('g', flag_ct),
    ]
    archive = build_archive(entries)

    key_table = [bytes(rng.getrandbits(8) for _ in range(16)) for _ in range(KEY_TABLE_SIZE)]
    layer1 = encrypt_layer(archive, key_table)
    layer2 = encrypt_layer(layer1, key_table)
    with open('dist/feed.bin', 'wb') as f:
        f.write(layer2)
    print(f'wrote dist/feed.bin ({len(layer2)} bytes)')

    # Reference build info — NOT shipped in dist/.
    with open('build/shipped_keypair.hex', 'w') as f:
        f.write(f'winning ticket:  {TICKET.hex()}\n')
        f.write(f'flag_km (K||IV): {km.hex()}\n')
        f.write(f'flag:            {FLAG_PLAINTEXT.decode()}\n')

    # XOR-masked AES key table, embedded into the binary.
    def mask_py(i, j):
        return (((i + 1) * 0x9E) & 0xFF) ^ (((j + 1) * 0x37) & 0xFF) ^ 0x5A
    masked = [bytes(key_table[i][j] ^ mask_py(i, j) for j in range(16))
              for i in range(KEY_TABLE_SIZE)]
    with open('src/blob_key_table.c', 'w') as f:
        f.write('/* Auto-generated by build/build_blob.py - do not edit. */\n')
        f.write('#include <stdint.h>\n')
        f.write('#include "blob.h"\n\n')
        f.write(f'static const uint8_t KT[{KEY_TABLE_SIZE}][16] = {{\n')
        for k in masked:
            bs = ', '.join(f'0x{b:02x}' for b in k)
            f.write(f'    {{ {bs} }},\n')
        f.write('};\n\n')
        f.write('void blob_get_key(unsigned i, uint8_t out[16]){\n')
        f.write('    for(unsigned j=0; j<16; j++){\n')
        f.write('        uint8_t m = (uint8_t)((i+1) * 0x9Eu) ^\n')
        f.write('                    (uint8_t)((j+1) * 0x37u) ^ (uint8_t)0x5Au;\n')
        f.write('        out[j] = KT[i][j] ^ m;\n')
        f.write('    }\n')
        f.write('}\n')
    print('wrote src/blob_key_table.c')

if __name__ == '__main__':
    main()
