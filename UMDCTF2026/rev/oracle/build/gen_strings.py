#!/usr/bin/env python3
"""Emit the encoded string pool + per-string 4-arg macros.

Each call site passes 4 32-bit args that combine with pool constants to
derive the pool offset, length, and XOR mask:
    offset = a0 ^ a2 ^ XOR_CONST
    length = a1 ^ a3 ^ V20_0
    mask   = pack('<II', a1 ^ V20_0, a2 ^ V20_1)
A 2-byte header at each pool entry XORs with a1 to the magic 0x7DD1.
"""
import random, struct, sys, os

# Keep this aligned with xorstr.h
DECODERS = {
    'A': dict(xor=0x3BF1F5AA, v0=0x7154F8C0, v1=0x9B27C67F),
    'B': dict(xor=0xB44E2B42, v0=0x474F87D2, v1=0x329BD061),
}

# List of (macro_name, variant, plaintext)
STRINGS = [
    ('S_BANNER',            'A', "oracle v1 - market settlement verifier"),
    ('S_OPEN_LICENSE',      'A', "ticket.txt"),
    ('S_PEM_BEGIN',         'B', "-----BEGIN MARKET TICKET-----"),
    ('S_PEM_END',           'B', "-----END MARKET TICKET-----"),
    ('S_REJECT',            'A', "ticket rejected"),
    ('S_LOAD_BLOB',         'B', "feed.bin"),
    ('S_ENTRY_MAIN',        'B', "a"),
    ('S_ENTRY_VALIDATE',    'B', "b"),
    ('S_ENTRY_FLAGSEAL',    'B', "g"),
    ('S_FLAG_HDR',          'B', "resolution: "),
]

# Fixed randomness so the build is reproducible
rng = random.Random(0xC0FFEE)

pool_bytes = {'A': bytearray(), 'B': bytearray()}
macros = []

for name, variant, text in STRINGS:
    dec = DECODERS[variant]
    data = text.encode('utf-8')
    length = len(data)

    # Pick a1, a2 randomly; derive a0, a3 from offset & length
    a1 = rng.randint(0, 0xFFFFFFFF)
    a2 = rng.randint(0, 0xFFFFFFFF)

    mask_lo = (a1 ^ dec['v0']) & 0xFFFFFFFF
    mask_hi = (a2 ^ dec['v1']) & 0xFFFFFFFF
    mask = struct.pack('<II', mask_lo, mask_hi)

    # The 2-byte header must satisfy (hdr ^ a1) & 0xFFFF == 0x7DD1
    hdr = (0x7DD1 ^ (a1 & 0xFFFF)) & 0xFFFF
    hdr_bytes = struct.pack('<H', hdr)

    enc = bytes(b ^ mask[i & 7] for i, b in enumerate(data))

    # Append to pool, capture offset
    offset = len(pool_bytes[variant])
    pool_bytes[variant] += hdr_bytes
    pool_bytes[variant] += enc

    # Derive a0 so that (a0 ^ a2 ^ xor_const) == offset
    a0 = (offset ^ a2 ^ dec['xor']) & 0xFFFFFFFF
    # Derive a3 so that (a3 ^ a1 ^ v20_0) == length
    a3 = (length ^ a1 ^ dec['v0']) & 0xFFFFFFFF

    # Buffer needs length+1 bytes; caller supplies
    func = 'xsA' if variant == 'A' else 'xsB'
    macros.append((name, func, a0, a1, a2, a3, length))

# Emit strings.inc
out_h = []
out_h.append('/* Auto-generated by build/gen_strings.py - do not edit. */')
out_h.append('#ifndef STRINGS_INC_H')
out_h.append('#define STRINGS_INC_H')
out_h.append('#include "xorstr.h"')
out_h.append('')
for name, func, a0, a1, a2, a3, length in macros:
    # +1 for the NUL terminator
    out_h.append(f'#define {name}_LEN {length}')
    out_h.append(f'#define {name}(buf) {func}((buf), 0x{a0:08x}u, 0x{a1:08x}u, 0x{a2:08x}u, 0x{a3:08x}u)')
out_h.append('')
out_h.append('/* Max length of any encoded string (for local buffers). */')
max_len = max(m[6] for m in macros)
out_h.append(f'#define XS_MAX_LEN {max_len}')
out_h.append('')
out_h.append('#endif')

os.makedirs('src', exist_ok=True)
with open('src/strings.inc.h', 'w') as f:
    f.write('\n'.join(out_h) + '\n')

# Emit strings_pool.c with the two byte arrays
with open('src/strings_pool.c', 'w') as f:
    f.write('/* Auto-generated by build/gen_strings.py - do not edit. */\n')
    f.write('#include <stdint.h>\n\n')
    for v in ('A', 'B'):
        f.write(f'const uint8_t xs{v}_pool[] = {{\n    ')
        for i, b in enumerate(pool_bytes[v]):
            f.write(f'0x{b:02x},')
            if (i + 1) % 16 == 0:
                f.write('\n    ')
            else:
                f.write(' ')
        f.write('\n};\n\n')

print(f'Generated {len(STRINGS)} strings. Pool A: {len(pool_bytes["A"])}B, Pool B: {len(pool_bytes["B"])}B')
