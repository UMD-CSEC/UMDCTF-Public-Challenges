static const uint8_t rcon[11]={0x00,0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1b,0x36};

void aes128_key_expand(const uint8_t key[16], uint8_t rk[176]){
    memcpy(rk, key, 16);
    for(int i=16, r=1; i<176; i+=4){
        uint8_t t[4]={rk[i-4],rk[i-3],rk[i-2],rk[i-1]};
        if(i%16==0){
            uint8_t tt=t[0]; t[0]=t[1]; t[1]=t[2]; t[2]=t[3]; t[3]=tt;
            t[0]=sbox[t[0]]; t[1]=sbox[t[1]]; t[2]=sbox[t[2]]; t[3]=sbox[t[3]];
            t[0]^=rcon[r++];
        }
        rk[i]  =rk[i-16]^t[0];
        rk[i+1]=rk[i-15]^t[1];
        rk[i+2]=rk[i-14]^t[2];
        rk[i+3]=rk[i-13]^t[3];
    }
}

static uint8_t xtime(uint8_t x){ return (uint8_t)((x<<1) ^ ((x>>7)*0x1b)); }
static uint8_t mul(uint8_t x, uint8_t y){
    uint8_t r=0;
    for(int i=0;i<8;i++){
        if(y&1) r^=x;
        x = xtime(x);
        y >>= 1;
    }
    return r;
}

static void add_rk(uint8_t s[16], const uint8_t *k){ for(int i=0;i<16;i++) s[i]^=k[i]; }
static void sub_bytes(uint8_t s[16]){ for(int i=0;i<16;i++) s[i]=sbox[s[i]]; }
static void inv_sub_bytes(uint8_t s[16]){ for(int i=0;i<16;i++) s[i]=inv_sbox[s[i]]; }
static void shift_rows(uint8_t s[16]){
    uint8_t t;
    t=s[1]; s[1]=s[5]; s[5]=s[9]; s[9]=s[13]; s[13]=t;
    t=s[2]; s[2]=s[10]; s[10]=t; t=s[6]; s[6]=s[14]; s[14]=t;
    t=s[3]; s[3]=s[15]; s[15]=s[11]; s[11]=s[7]; s[7]=t;
}
static void inv_shift_rows(uint8_t s[16]){
    uint8_t t;
    t=s[13]; s[13]=s[9]; s[9]=s[5]; s[5]=s[1]; s[1]=t;
    t=s[2]; s[2]=s[10]; s[10]=t; t=s[6]; s[6]=s[14]; s[14]=t;
    t=s[7]; s[7]=s[11]; s[11]=s[15]; s[15]=s[3]; s[3]=t;
}
static void mix_cols(uint8_t s[16]){
    for(int c=0;c<4;c++){
        uint8_t *p=&s[c*4];
        uint8_t a0=p[0],a1=p[1],a2=p[2],a3=p[3];
        uint8_t t=a0^a1^a2^a3;
        p[0]^=t^xtime(a0^a1);
        p[1]^=t^xtime(a1^a2);
        p[2]^=t^xtime(a2^a3);
        p[3]^=t^xtime(a3^a0);
    }
}
static void inv_mix_cols(uint8_t s[16]){
    for(int c=0;c<4;c++){
        uint8_t *p=&s[c*4];
        uint8_t a0=p[0],a1=p[1],a2=p[2],a3=p[3];
        p[0]=mul(a0,0x0e)^mul(a1,0x0b)^mul(a2,0x0d)^mul(a3,0x09);
        p[1]=mul(a0,0x09)^mul(a1,0x0e)^mul(a2,0x0b)^mul(a3,0x0d);
        p[2]=mul(a0,0x0d)^mul(a1,0x09)^mul(a2,0x0e)^mul(a3,0x0b);
        p[3]=mul(a0,0x0b)^mul(a1,0x0d)^mul(a2,0x09)^mul(a3,0x0e);
    }
}

void aes128_encrypt_block(const uint8_t rk[176], const uint8_t in[16], uint8_t out[16]){
    uint8_t s[16]; memcpy(s,in,16);
    add_rk(s, rk);
    for(int r=1;r<10;r++){
        sub_bytes(s); shift_rows(s); mix_cols(s); add_rk(s, rk + r*16);
    }
    sub_bytes(s); shift_rows(s); add_rk(s, rk + 10*16);
    memcpy(out,s,16);
}

void aes128_decrypt_block(const uint8_t rk[176], const uint8_t in[16], uint8_t out[16]){
    uint8_t s[16]; memcpy(s,in,16);
    add_rk(s, rk+10*16);
    for(int r=9;r>0;r--){
        inv_shift_rows(s); inv_sub_bytes(s); add_rk(s, rk + r*16); inv_mix_cols(s);
    }
    inv_shift_rows(s); inv_sub_bytes(s); add_rk(s, rk);
    memcpy(out,s,16);
}

int aes128_cbc_decrypt(const uint8_t key[16], const uint8_t iv[16],
                       uint8_t *buf, size_t len, int strip_pkcs7){
    if(len==0 || (len%16)!=0) return -1;
    uint8_t rk[176]; aes128_key_expand(key, rk);
    uint8_t prev[16]; memcpy(prev, iv, 16);
    uint8_t tmp[16], ct[16];
    for(size_t off=0; off<len; off+=16){
        memcpy(ct, buf+off, 16);
        aes128_decrypt_block(rk, ct, tmp);
        for(int i=0;i<16;i++) buf[off+i] = tmp[i] ^ prev[i];
        memcpy(prev, ct, 16);
    }
    if(strip_pkcs7){
        uint8_t pad = buf[len-1];
        if(pad==0 || pad>16) return -1;
        for(size_t i=0;i<pad;i++) if(buf[len-1-i]!=pad) return -1;
        return (int)(len - pad);
    }
    return (int)len;
}
